-- O histórico guarda a identidade autenticada do autor e os detalhes da ação.
CREATE TABLE IF NOT EXISTS public.vizzion_activity_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    action TEXT NOT NULL,
    entity_type TEXT NOT NULL DEFAULT 'general',
    entity_id TEXT,
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_vizzion_activity_created_at
    ON public.vizzion_activity_log (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_vizzion_activity_user_id
    ON public.vizzion_activity_log (user_id);

ALTER TABLE public.vizzion_activity_log ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.vizzion_activity_log FROM anon, authenticated;
GRANT ALL ON public.vizzion_activity_log TO service_role;
